import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ComparisonDashboard } from '../components/ComparisonDashboard';
import { MOCK_SIMULATION_RESULT } from '../services/mockData';
import type { RunManifest, SimulationConfig, SimulationOutput } from '../types';
import { createExperimentAssignment } from '../services/experimentProtocol';
const service = await import('../services/experimentResults').catch(() => null);
assert.ok(service, 'condition summaries must validate pairing from manifests');
const result = (condition: string, replica: string, value: number): SimulationOutput => ({ ...MOCK_SIMULATION_RESULT, frameworkName: 'Same label', summary: { ...MOCK_SIMULATION_RESULT.summary, totalRoi: value },
    manifest: { schemaVersion: 1, runId: `${condition}-${replica}`, experimentId: 'test', replicaId: replica, scenarioId: 'fixed', scenarioSeed: 71, interventionId: condition, configHash: 'c'.repeat(64), datasetHash: 'd'.repeat(64), codeRevision: 'a'.repeat(40), startedAt: '2026-10-04T00:00:00Z', dataSource: 'synthetic', empiricalValidation: 'pending', executionMode: 'live', models: [], rubricVersion: 'v1', rubricHash: 'b'.repeat(64), memoryPolicy: 'isolated', protocol: createExperimentAssignment({ seed: 71, durationMonths: 2, scenarioContext: 'fixed' }, { experimentId: 'test', replicaId: replica, interventionId: condition }) } as RunManifest });
const outputs = [result('a', '1', -10), result('b', '1', -15), result('a', '2', -20), result('b', '2', -25)];
const report = service.compareConditions(outputs);
assert.equal(report.conditions.length, 2, 'labels are not identity');
assert.equal(report.conditions[0].statistics.mean, -15);
assert.equal(report.comparisons[0].statistics.delta, -5);
assert.equal(report.comparisons[0].statistics.nIndependent, 2);
const mismatch = structuredClone(outputs); mismatch[1].manifest!.datasetHash = 'f'.repeat(64);
assert.equal(service.compareConditions(mismatch).comparisons[0].statistics.nExcluded, 1);
assert.equal(service.compareConditions(outputs.slice(0, 3)).comparisons[0].statistics.nExcluded, 1, 'missing arms remain in the planned pair set');
const codeMismatch = structuredClone(outputs);
codeMismatch.forEach(output => { output.manifest!.codeStateHash = '1'.repeat(64); });
codeMismatch[1].manifest!.codeStateHash = '2'.repeat(64);
assert.equal(service.compareConditions(codeMismatch).comparisons[0].statistics.nExcluded, 1, 'equal HEAD revisions do not hide different local source snapshots');
const markup = renderToStaticMarkup(<ComparisonDashboard results={outputs} config={{ frameworks: [], companySize: 20, sector: 'tech' } as unknown as SimulationConfig} onReset={() => undefined} />);
assert.ok(!markup.includes('Recomendação da Engine') && !markup.includes('opção mais eficiente'), 'no uncalibrated composite verdict');
assert.ok(markup.includes('Delta pareado'));
assert.ok(markup.includes('-15'), 'negative outcomes remain visible');
assert.ok(markup.includes('n independente'));
assert.ok(markup.includes('Validação empírica pendente'));
console.log('  ✓ condition identity, evidence of pairing, missing arms, losses and comparative UI');
